export function getServiceGroupForCatalogItem(
  item: ServiceCatalogItem
): ServiceGroupCategory {
  if (item.platformStatus === 'COMING SOON' || item.category === 'Hotel') {
    return 'Future V2 Services — Planned Only';
  }
  if (item.category === 'Restaurant') return 'Restaurant Operations';
  if (item.category === 'Resource Management') return 'Resource Management';
  if (item.category === 'Core') return 'Platform Services';
  return 'Business Management';
}

