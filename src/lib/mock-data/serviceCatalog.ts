export function getServiceById(serviceId: ServiceId): ServiceCatalogItem | undefined {
  return SERVICE_CATALOG.find((s) => s.id === serviceId);
}

/**
 * Returns all services in the catalog that directly or transitively depend on `targetServiceId`
 */
export function getDependentServices(targetServiceId: ServiceId): ServiceCatalogItem[] {
  return SERVICE_CATALOG.filter(
    (item) =>
      item.platformStatus === 'AVAILABLE' &&
      item.dependencies.includes(targetServiceId)
  );
}

export function getMissingDependencies(
  targetServiceId: ServiceId,
  activeServiceIds: ServiceId[]
): ServiceId[] {
  const item = getServiceById(targetServiceId);
  if (!item) return [];
  return item.dependencies.filter((depId) => !activeServiceIds.includes(depId));
}


